func TestParseStartApps(t *testing.T) {
	t.Run("array", func(t *testing.T) {
		apps, err := ParseStartApps([]byte(`[{"Name":"Calculator","AppID":"Microsoft.WindowsCalculator_8wekyb3d8bbwe!App"},{"Name":"Notepad","AppID":"Microsoft.AutoGenerated.{abc}"}]`))
		if err != nil {
			t.Fatal(err)
		}
		if len(apps) != 1 {
			t.Fatalf("classic AppIDs (no \"!\") must be filtered, got %+v", apps)
		}
		if apps[0].Name != "Calculator" || apps[0].AppID != "Microsoft.WindowsCalculator_8wekyb3d8bbwe!App" {
			t.Fatalf("app: %+v", apps[0])
		}
	})

	t.Run("single object", func(t *testing.T) {
		// ConvertTo-Json emits a bare object when there is exactly one.
		apps, err := ParseStartApps([]byte(`{"Name":"Windows Terminal","AppID":"Microsoft.WindowsTerminal_8wekyb3d8bbwe!App"}`))
		if err != nil {
			t.Fatal(err)
		}
		if len(apps) != 1 || apps[0].Name != "Windows Terminal" {
			t.Fatalf("apps: %+v", apps)
		}
	})

	t.Run("empty", func(t *testing.T) {
		apps, err := ParseStartApps(nil)
		if err != nil || len(apps) != 0 {
			t.Fatalf("got %+v, %v", apps, err)
		}
	})

	t.Run("junk", func(t *testing.T) {
		if _, err := ParseStartApps([]byte("not json")); err == nil {
			t.Fatal("want an error")
		}
	})

	t.Run("duplicates and nameless rows", func(t *testing.T) {
		apps, err := ParseStartApps([]byte(`[
			{"Name":"Calculator","AppID":"Microsoft.WindowsCalculator_8wekyb3d8bbwe!App"},
			{"Name":"Calculator","AppID":"microsoft.windowscalculator_8wekyb3d8bbwe!App"},
			{"Name":"","AppID":"Microsoft.X_8wekyb3d8bbwe!App"}
		]`))
		if err != nil {
			t.Fatal(err)
		}
		if len(apps) != 1 {
			t.Fatalf("duplicates and nameless rows must be dropped, got %+v", apps)
		}
	})
}

func TestStoreSourceCachesSuccess(t *testing.T) {
	calls := 0
	src := &StoreSource{Run: func(ctx context.Context) ([]StoreApp, error) {
		calls++
		return []StoreApp{{Name: "A", AppID: "a!b"}}, nil
	}}
	for i := 0; i < 3; i++ {
		apps, err := src.Apps(context.Background())
		if err != nil || len(apps) != 1 {
			t.Fatalf("call %d: %+v, %v", i, apps, err)
		}
	}
	if calls != 1 {
		t.Fatalf("Run called %d times, want 1 (cached)", calls)
	}
}

func TestStoreSourceRetriesFailure(t *testing.T) {
	calls := 0
	src := &StoreSource{Run: func(ctx context.Context) ([]StoreApp, error) {
		calls++
		if calls == 1 {
			return nil, errors.New("powershell blocked")
		}
		return []StoreApp{{Name: "A", AppID: "a!b"}}, nil
	}}
	if _, err := src.Apps(context.Background()); err == nil {
		t.Fatal("first call must fail")
	}
	apps, err := src.Apps(context.Background())
	if err != nil || len(apps) != 1 {
		t.Fatalf("second call: %+v, %v", apps, err)
	}
	if calls != 2 {
		t.Fatalf("Run called %d times, want 2", calls)
	}
}

func TestStoreSourceNilRun(t *testing.T) {
	src := &StoreSource{}
	apps, err := src.Apps(context.Background())
	if err != nil || apps != nil {
		t.Fatalf("got %+v, %v", apps, err)
	}
}
